/* feedback-3 계약이 정한 값: 버전, capability bit, status, reason, quality bit.
 * 계약 docs/contracts/gateway-feedback-3.md §4·§7 */
#ifndef XENOVA_FB3_CODES_H
#define XENOVA_FB3_CODES_H

#include <stdint.h>

#define FB3_VERSION 3u

/* 순번과 시각은 1..2^63-1 만 쓴다 */
#define FB3_U63_MAX UINT64_C(0x7fffffffffffffff)

/* HELLO_ACK capabilities. 구현한 기능만 알린다 */
#define FB3_CAP_ACCEPT 0x0001u
#define FB3_CAP_APPLY 0x0002u
#define FB3_CAP_VELOCITY 0x0004u
#define FB3_CAP_STEERING 0x0008u
#define FB3_CAP_STATIONARY 0x0010u
#define FB3_CAP_ODOMETRY 0x0020u
#define FB3_CAP_ABS_EXPIRY 0x0040u
#define FB3_CAP_CLOCK4_LATCH 0x0080u
#define FB3_CAP_DIRECTION_GATE 0x0100u
#define FB3_CAP_TOF_FRAGMENT 0x0200u /* 8x8 조각 전송. 지금 계약에서는 쓰지 않는다 */
#define FB3_CAP_STATIONARY_STEER 0x0400u
#define FB3_CAP_TOF_SINGLE 0x0800u   /* 단일 존 TOF_SAMPLE */
#define FB3_CAP_PROXIMITY_GUARD 0x1000u /* ToF 로 가까운 물체를 보면 그 방향의 출력을 끊는다 */

/* CLOCK_ACK status */
#define FB3_CLOCK_INSTALLED 1u
#define FB3_CLOCK_REJECTED 3u

/* COMMAND command_kind */
#define FB3_COMMAND_DRIVE 1u
#define FB3_COMMAND_STOP 2u
#define FB3_COMMAND_HOLD_STEER 3u
/* COMMAND reason 의 가장 큰 값 */
#define FB3_COMMAND_REASON_MAX 10u
/* DRIVE 의 expires_pi_us 는 issued_pi_us 에서 이 안이어야 한다 */
#define FB3_COMMAND_LIFE_US 100000u

/* REPORT status */
#define FB3_REPORT_ACCEPTED 1u
#define FB3_REPORT_APPLIED 2u
#define FB3_REPORT_REJECTED 3u
#define FB3_REPORT_FAULT 4u

/* REPORT flags. 값이 실려 있는 측정 */
#define FB3_REPORT_VELOCITY 0x01u
#define FB3_REPORT_STEERING 0x02u
#define FB3_REPORT_STATIONARY 0x04u

/* CLOCK_REPLY·SENSOR quality. 조향은 측정과 추정 중 하나만 */
#define FB3_QUALITY_ENCODER 0x01u
#define FB3_QUALITY_STEERING_MEASURED 0x02u
#define FB3_QUALITY_STEERING_ESTIMATED 0x04u
/* 근거리 제동이 그 방향을 막고 있다. PROXIMITY_GUARD 를 알린 장치만 쓴다 */
#define FB3_QUALITY_FRONT_BLOCKED 0x08u
#define FB3_QUALITY_REAR_BLOCKED 0x10u
#define FB3_STEERING_LIMIT_MRAD 1400

/* TOF_SAMPLE frame_status */
#define FB3_TOF_FRAME_SENSOR_OK 0x0001u
#define FB3_TOF_FRAME_TIMING_VALID 0x0002u
#define FB3_TOF_FRAME_TARGET_REDUCTION 0x0004u

/* TOF_SAMPLE status. 센서의 native 상태를 이 값으로 바꿔 싣는다 */
#define FB3_TOF_UNKNOWN 0u
#define FB3_TOF_VALID 1u
#define FB3_TOF_NO_TARGET 2u
#define FB3_TOF_OUT_OF_RANGE 3u
#define FB3_TOF_SATURATED 4u
#define FB3_TOF_SENSOR_ERROR 5u
#define FB3_TOF_STALE 6u
#define FB3_TOF_BAD_RETURN 7u

/* TOF_SAMPLE quality. TARGET_VALID 는 status 가 VALID 이고 거리가 1..65534 일 때만 켠다 */
#define FB3_TOF_QUALITY_TARGET_VALID 0x01u
#define FB3_TOF_QUALITY_NATIVE 0x02u
#define FB3_TOF_QUALITY_SECOND_TARGET 0x04u
#define FB3_TOF_QUALITY_REDUCED 0x08u
#define FB3_TOF_QUALITY_FREE_BLOCKED 0x10u

/* CLOCK_ACK·REPORT 공통 reason */
enum fb3_reason {
	FB3_REASON_OK = 0,
	FB3_REASON_BAD_LENGTH = 1,
	FB3_REASON_BAD_CRC = 2,
	FB3_REASON_SESSION_MISMATCH = 3,
	FB3_REASON_SEQUENCE_REPLAY = 4,
	FB3_REASON_IDEMPOTENCY_CONFLICT = 5,
	FB3_REASON_CLOCK_UNAVAILABLE = 6,
	FB3_REASON_CLOCK_EXPIRED = 7,
	FB3_REASON_COMMAND_EXPIRED = 8,
	FB3_REASON_RANGE = 9,
	FB3_REASON_DIRECTION_STOP_REQUIRED = 10,
	FB3_REASON_DEVICE_FAULT = 11,
	FB3_REASON_CONFIG_MISMATCH = 12,
	FB3_REASON_COUNTER_EXHAUSTED = 13,
	FB3_REASON_E_STOP = 14,
	FB3_REASON_GENERATION_REPLAY = 15,
	FB3_REASON_UNSUPPORTED_PROFILE = 16,
	FB3_REASON_TIMESTAMP_ORDER = 17,
	FB3_REASON_SENSOR_UNAVAILABLE = 18,
	FB3_REASON_DEADLINE_MISMATCH = 19,
	FB3_REASON_CLOCK_DRIFT = 20,
	FB3_REASON_PROXIMITY_BLOCKED = 21, /* 근거리 제동이 막고 있는 방향의 DRIVE. REPORT 에서만 쓴다 */
	FB3_REASON_COUNT
};

#endif
